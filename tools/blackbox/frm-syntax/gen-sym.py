# Symmetry qualifier tests: inputs/y.frm and cases-y.txt.
# Every entry has the same body, which has no mirror symmetry of its own, so
# any symmetry in the saved image comes from the header qualifier.
import os
here = os.path.dirname(os.path.abspath(__file__))
body = ('  z = pixel:\n'
        '  z = z*z + (0.3,0.4)*pixel + (0.1,0.1) + 0.01*p1\n'
        '  |z| <= 4\n')
syms = ['', 'XAXIS', 'YAXIS', 'XYAXIS', 'ORIGIN', 'PI_SYM', 'XAXIS_NOPARM', 'XAXIS_NOREAL',
        'XAXIS_NOIMAG', 'YAXIS_NOPARM', 'XYAXIS_NOPARM', 'ORIGIN_NOPARM', 'PI_SYM_NOPARM',
        'NOSYM', 'BOGUS', 'xaxis', 'NONE', 'X AXIS', 'xaxis junk']
ents, cases = [], []
for i, s in enumerate(syms):
    name = f'y{i:02d}'
    hdr = f'{name}({s}) {{' if s else f'{name} {{'
    ents.append(hdr + '\n' + body + '}\n')
    tag = f'{i:02d}-' + (s.lower().replace(' ', '-') or 'plain')
    cases.append(f'y-{tag} formulafile=y.frm formulaname={name}')
    if 'NO' in s and s != 'NOSYM' and s != 'NONE':
        for pv, pt in [('0.5/0', 're'), ('0/0.5', 'im'), ('0.5/0.5', 'both')]:
            cases.append(f'y-{tag}-p{pt} formulafile=y.frm formulaname={name} params={pv}')
cases.append('y-01-xaxis-symnone formulafile=y.frm formulaname=y01 symmetry=none')
cases.append('y-00-plain-symx formulafile=y.frm formulaname=y00 symmetry=xaxis')
cases.append('y-01-xaxis-symy formulafile=y.frm formulaname=y01 symmetry=yaxis')
with open(os.path.join(here, 'inputs', 'y.frm'), 'w') as f:
    f.write('; SPDX-License-Identifier: GPL-3.0-or-later\n; Symmetry qualifier tests (gen-sym.py)\n')
    f.writelines(ents)
with open(os.path.join(here, 'cases-y.txt'), 'w') as f:
    f.write('# SPDX-License-Identifier: GPL-3.0-or-later\n# Generated by gen-sym.py: symmetry qualifiers.\n')
    f.write('\n'.join(cases) + '\n')
print(len(cases))
