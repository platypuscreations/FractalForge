# Builds a "probe" formula file and a cases file from a list of expressions.
#   python3 -I gen-probe.py LIST PREFIX
# LIST has lines "name<TAB>init-statements<TAB>extra-args" (# comments allowed).
# Each entry is
#   name {
#     z = 0, INIT:
#     z = z + 1
#     real(z) <= real(k)
#   }
# A literal \n (backslash, n) in INIT starts a new line.
# so (cal-*: confirmed) the saved colour index is floor(k) + 1 for
# 0 <= k < 254 and 1 for k < 1; the init statements must set k.
# Writes inputs/PREFIX.frm and cases-PREFIX.txt (maxiter=1000).
import sys, os
here = os.path.dirname(os.path.abspath(__file__))
lst, prefix = sys.argv[1], sys.argv[2]
ents, cases = [], []
for line in open(lst):
    line = line.rstrip('\n')
    if not line.strip() or line.startswith('#'):
        continue
    name, init, *rest = line.split("\t")
    extra = rest[0] if rest else ''
    init = init.replace('\\n', '\n  ')
    ents.append(f'{name} {{\n  z = 0, {init}:\n  z = z + 1\n  real(z) <= real(k)\n}}\n')
    cases.append(f'{prefix}-{name} formulafile={prefix}.frm formulaname={name} maxiter=1000 {extra}'.rstrip())
with open(os.path.join(here, 'inputs', prefix + '.frm'), 'w') as f:
    f.write('; SPDX-License-Identifier: GPL-3.0-or-later\n; Generated by gen-probe.py from ' + os.path.basename(lst) + '\n')
    f.writelines(ents)
with open(os.path.join(here, 'cases-' + prefix + '.txt'), 'w') as f:
    f.write('# SPDX-License-Identifier: GPL-3.0-or-later\n# Generated by gen-probe.py from ' + os.path.basename(lst) + '\n')
    f.write('\n'.join(cases) + '\n')
