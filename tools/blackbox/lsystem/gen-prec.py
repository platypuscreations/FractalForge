# Precision probe: writes inputs/prec.l and cases-prec.txt.  Entry tM_D
# draws one horizontal segment from the turtle origin whose right end lies,
# in exact arithmetic, at pixel column M + 0.5 + delta (400x300 image).  The
# frame (moves only) spans -0.1 .. 1 unit, so the scale is 390/1.1 pixels
# per unit and the origin sits at column 39.9545...  Comparing the saved end
# column with the exact value shows how precise XFractint's arithmetic is.
#   python3 -I gen-prec.py
import os
from fractions import Fraction as Fr
here = os.path.dirname(os.path.abspath(__file__))
L = []; C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-prec.py.']
DEL = ['3e-1', '-3e-1', '1e-2', '-1e-2', '1e-3', '-1e-3', '1e-4', '-1e-4', '1e-5', '-1e-5',
       '3e-6', '-3e-6', '1e-6', '-1e-6', '3e-7', '-3e-7', '1e-7', '-1e-7', '1e-8', '-1e-8', '1e-10', '-1e-10']
for m in (300, 150, 60):
    for dl in DEL:
        d = Fr(dl)
        a = (Fr(11, 10) * (m + Fr(1, 2) + d) - Fr(4395, 100)) / 390
        txt = f'{float(a):.17f}'
        name = f't{m}_{dl.replace("-", "m")}'
        L += [f'{name} {{', '  angle 4', f'  axiom [@{txt}F][|@0.1G]G', '}']
        C.append(f'prec-{name} only=prec.l,uniq.map type=lsystem lfile=prec.l lname={name} params=0 viewwindows=2 map=uniq.map')
open(os.path.join(here, 'inputs', 'prec.l'), 'w').write('\n'.join(L) + '\n')
open(os.path.join(here, 'cases-prec.txt'), 'w').write('\n'.join(C) + '\n')
