# Move and degree-turn commands and arrowhead-type curves: writes
# inputs/mv.l, inputs/deg.l, inputs/deg2.l, inputs/arr.l and cases-mv.txt,
# cases-deg.txt, cases-deg2.txt, cases-arr.txt.
#   python3 -I gen-turtle.py
import os
here = os.path.dirname(os.path.abspath(__file__))
def w(name, text): open(os.path.join(here, name), 'w').write(text)
HDR = '# SPDX-License-Identifier: GPL-3.0-or-later\n# Generated by gen-turtle.py.\n'
# --- moves in every context (entry mNN = axiom number NN)
MV = ['F+G','F+M','F+g','F+m','G+F','M+F','g+F','m+F','D+F','F+D','d+F','f+F','FG+F','FM+F','Fg+F','Fm+F',
      'F+GF','F+MF','F+gF','F+mF','DM+D','DG+D','FM+F','FMF','F-MF','F|MF','FM-F','FM|F','GG+F','MM+F',
      'FMM+F','FGM+F','FMG+F','F[M]+F','FM[+F]']
L = []
for i, a in enumerate(MV): L += [f'm{i:02d} {{', '  angle 4', f'  axiom {a}', '}']
w('inputs/mv.l', '\n'.join(L) + '\n')
w('cases-mv.txt', HDR + ''.join(f'mv-m{i:02d} only=mv.l,uniq.map type=lsystem lfile=mv.l lname=m{i:02d} params=0 viewwindows=2 map=uniq.map\n' for i in range(len(MV))))
# --- degree turns with angle 4 and 7 (entry dNNaA)
DG = ['D/90D','D\\90D','D/45D','D/30D','D\\30D','D/90/90D','D/450D','D/90.5D','D/90F','F/90D','D!/90D','D!\\90D',
      'D[/90D]D','D/90MD','D/90[D]+D','D@2/90D','D/1D','D/0.5D','D/0D','D/360D','D/-90D','D/90+D','D+/90D','D/90|D',
      'F/90+F','D/89.99D','D/120D/120D']
L = []; C = []
for i, a in enumerate(DG):
    for ang in (4, 7):
        L += [f'd{i:02d}a{ang} {{', f'  angle {ang}', f'  axiom {a}', '}']
        C.append(f'deg-d{i:02d}a{ang} only=deg.l,uniq.map type=lsystem lfile=deg.l lname=d{i:02d}a{ang} params=0 viewwindows=2 map=uniq.map')
w('inputs/deg.l', '\n'.join(L) + '\n'); w('cases-deg.txt', HDR + '\n'.join(C) + '\n')
# --- accumulated degree turns: n turns of X degrees (n*X = 90 or 420 ...)
AX = []
for X, n in ((1,90),(3,30),(7.5,12),(9,10),(10,9),(11.25,8),(15,6),(18,5),(22.5,4),(30,3),(45,2),(0.1,900),(2.5,36),
             (12.5,36),(6,45),(36,10),(13,7),(17,11),(0.3,300),(4.5,40),(7,60)):
    AX.append('D' + f'/{X:g}' * n + 'D'); AX.append('D' + f'\\{X:g}' * n + 'D')
L = []
for i, a in enumerate(AX): L += [f'e{i:02d} {{', '  angle 4', f'  axiom {a}', '}']
w('inputs/deg2.l', '\n'.join(L) + '\n')
w('cases-deg2.txt', HDR + ''.join(f'deg2-e{i:02d} only=deg2.l,uniq.map type=lsystem lfile=deg2.l lname=e{i:02d} params=0 viewwindows=2 map=uniq.map\n' for i in range(len(AX))))
# --- arrowhead-type curves
w('inputs/arr.l', 'a1 {\n  angle 6\n  axiom F\n  F=G-F-G\n  G=F+G+F\n}\na2 {\n  angle 6\n  axiom XF\n  X=YF+XF+Y\n  Y=XF-YF-X\n}\n'
  'a3 {\n  angle 6\n  axiom F\n  F=F-G+F\n  G=GG\n}\na4 {\n  angle 12\n  axiom F\n  F=G-F-G\n  G=F+G+F\n}\n')
C = []
for e, os_ in (('a1', (3, 4, 5, 6, 7)), ('a2', (3, 4, 5, 6)), ('a3', (3, 4, 5, 6)), ('a4', (3, 4, 5))):
    for o in os_:
        for nm, vw in (('400x300', '2'), ('640x480', '1/0.75/no/640/480'), ('555x333', '1/0.75/no/555/333')):
            C.append(f'arr-{e}-o{o}-{nm} only=arr.l,uniq.map type=lsystem lfile=arr.l lname={e} params={o} viewwindows={vw} map=uniq.map')
w('cases-arr.txt', HDR + '\n'.join(C) + '\n')
