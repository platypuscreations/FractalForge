# Writes cases-rich.txt: the multi-segment curves of inputs/rich.l at
# several orders and image sizes (geometry and rounding evidence).
#   python3 -I gen-rich.py
import os
here = os.path.dirname(os.path.abspath(__file__))
SIZES = [('400x300', '2'), ('800x600', '1/0.75/no/800/600'), ('401x301', '1/0.75/no/401/301'), ('640x480', '1/0.75/no/640/480')]
ORD = {'r1': (1, 3), 'r2': (1, 3), 'r3': (2, 3), 'r4': (2, 3), 'r5': (2, 3), 'r6': (2, 4), 'r7': (2, 4), 'r8': (4, 8), 'r9': (2, 3)}
C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-rich.py.']
for nm, vw in SIZES:
    for e, os_ in ORD.items():
        for o in os_:
            C.append(f'rich-{nm}-{e}-o{o} only=rich.l,uniq.map type=lsystem lfile=rich.l lname={e} params={o} viewwindows={vw} map=uniq.map')
open(os.path.join(here, 'cases-rich.txt'), 'w').write('\n'.join(C) + '\n')
