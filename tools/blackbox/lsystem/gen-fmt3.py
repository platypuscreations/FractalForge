# Third round of file-format tests (file lookup, entry ends, name rules):
# writes inputs/fpNNN.l (one per case), the extra files named below, and
# cases-fmt3.txt.  Every case runs in a work directory holding only the files
# it lists (run-case.sh only=...).  No licence comments inside the .l files.
#   python3 -I gen-fmt3.py
import os
here = os.path.dirname(os.path.abspath(__file__))
inp = os.path.join(here, 'inputs')
SQ = ' angle 4\n axiom F+F+F\n'
HEX = ' angle 6\n axiom F+F\n'
def w(fn, text):
    open(os.path.join(inp, fn), 'w', newline='').write(text)
# shared files for the lookup tests (names fit DOS 8.3)
w('lka.l', 'd {\n' + HEX + '}\n')                 # no entry e
w('lkb.l', 'e {\n' + SQ + '}\n')                  # e = square
w('lkc.l', 'e {\n' + HEX + '}\n')                 # e = 60-degree turn
w('lkz.l', 'e {\n angle 8\n axiom F+F\n}\n')      # e = 45-degree turn
C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-fmt3.py.']
def case(name, files, args):
    C.append(f'f-{name} only={",".join(files + ["uniq.map"])} type=lsystem {args} viewwindows=2 map=uniq.map')
case('lk-noentry', ['lka.l', 'lkb.l'], 'lfile=lka.l lname=e params=0')
case('lk-own-b', ['lkb.l', 'lkc.l'], 'lfile=lkb.l lname=e params=0')
case('lk-own-c', ['lkb.l', 'lkc.l'], 'lfile=lkc.l lname=e params=0')
case('lk-noext-b', ['lkb.l', 'lkc.l'], 'lfile=lkb lname=e params=0')
case('lk-noext-c', ['lkb.l', 'lkc.l'], 'lfile=lkc lname=e params=0')
case('lk-upper-b', ['lkb.l', 'lkc.l'], 'lfile=LKB.L lname=e params=0')
case('lk-upper-c', ['lkb.l', 'lkc.l'], 'lfile=LKC.L lname=e params=0')
case('lk-nofile-bc', ['lkb.l', 'lkc.l'], 'lfile=nosuch.l lname=e params=0')
case('lk-nofile-cz', ['lkc.l', 'lkz.l'], 'lfile=nosuch.l lname=e params=0')
case('lk-nofile-ab', ['lka.l', 'lkb.l'], 'lfile=nosuch.l lname=e params=0')
case('lk-nofile-a', ['lka.l'], 'lfile=nosuch.l lname=e params=0')
case('lk-long-b', ['lkb.l'], 'lfile=lkbxxxxxxx.l lname=e params=0')
T = []
def t(name, text, lname='e', extra='params=0'):
    T.append((name, text, lname, extra))
t('brace-nextline', 'e\n{\n' + SQ + '}\n')
t('brace-nextline-empty', 'e\n{\n' + SQ + '}\n', lname=None)
t('second-noblank', 'd {\n' + HEX + '}e {\n' + SQ + '}\n')
t('name-upper', 'EeX {\n' + SQ + '}\n', lname='eex')
for n in (18, 19, 20):
    t(f'lname{n}', 'k'*n + ' {\n' + SQ + '}\n', lname='k'*n)
t('name18-file24', 'k'*24 + ' {\n' + SQ + '}\n', lname='k'*18)
for nm, tag in (('a-b', 'dash'), ('a.b', 'dot'), ('a_b', 'under'), ('a(b)', 'paren'),
                ('a!b', 'bang'), ('1abc', 'digit'), ('a/b', 'slash'), ('a=b', 'eq'), ('a[b', 'brack')):
    t(f'name-{tag}', nm + ' {\n' + SQ + '}\n', lname=nm)
t('name-glued', 'e{angle 4\n axiom F+F+F\n}\n')
t('last-wins', 'e {\n' + SQ + ' angle 6\n}\n')
t('last-wins-col0', 'e {\n' + SQ + 'angle 6\n}\n')
t('after-open-entry', 'e {\n' + SQ + 'f {\n angle 6\n}\n')
t('noclose-indented', 'e {\n' + SQ + ' angle 6\n')
t('noclose-col0', 'e {\n' + SQ + 'angle 6\n')
t('noclose-col0-close', 'e {\n' + SQ + 'angle 6\n}\n')
t('rule-brace', 'e {\n' + SQ + ' F={\n}\n', extra='params=1')
t('rule-close', 'e {\n' + SQ + ' F=F}\n angle 6\n}\n', extra='params=1')
t('axiom-close', 'e {\n angle 4\n axiom F+F+F}\n angle 6\n}\n')
t('axiom-open', 'e {\n angle 4\n axiom F+F+F{\n angle 6\n}\n')
t('comment-in-name', 'e;x {\n' + SQ + '}\n')
for i, (name, text, ln, extra) in enumerate(T, 1):
    fn = f'fp{i:03d}.l'
    w(fn, text)
    a = f'lfile={fn}' + (f' lname={ln}' if ln else '') + f' {extra}'
    case(name, [fn], a)
# names end at '(' and '[': look the same files up by the part before it
for name, ln in (('name-paren-a', 'a(b)'), ('name-brack-a', 'a[b')):
    fn = f'fp{[i for i, t_ in enumerate(T, 1) if t_[2] == ln][0]:03d}.l'
    case(name, [fn], f'lfile={fn} lname=a params=0')
open(os.path.join(here, 'cases-fmt3.txt'), 'w').write('\n'.join(C) + '\n')
