# Miscellaneous cases: float=yes, duplicate rules, slash turns with F only,
# viewwindows sizes, corners, extra params, maxiter/passes.  Uses
# inputs/geo.l, dup.l, sl.l, seg.l, sem.l and rich.l.  Writes cases-misc.txt.
#   python3 -I gen-misc.py
import os
here = os.path.dirname(os.path.abspath(__file__))
C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-misc.py.']
def c(name, files, args): C.append(f'{name} only={files},uniq.map type=lsystem {args} map=uniq.map')
for e in ('g1', 'g2', 'g3', 'g4', 'g5', 'g6', 'g7', 'g8', 'g9'):
    c(f'geo-{e}', 'geo.l', f'lfile=geo.l lname={e} viewwindows=2')
    c(f'geo-{e}-fl', 'geo.l', f'lfile=geo.l lname={e} viewwindows=2 float=yes')
for e, o in (('r1', 3), ('r5', 3), ('r6', 4), ('r7', 4), ('r8', 8)):
    c(f'fl-{e}-o{o}', 'rich.l', f'lfile=rich.l lname={e} params={o} viewwindows=2 float=yes')
    c(f'fl-{e}-o{o}-no', 'rich.l', f'lfile=rich.l lname={e} params={o} viewwindows=2 float=no')
for e in ('r1', 'r2', 'r3', 'r4', 'r5', 'r6'):
    for p in (1, 2):
        c(f'dup-{e}-p{p}', 'dup.l', f'lfile=dup.l lname={e} params={p} viewwindows=2')
for e in ('s1', 's2', 's3', 's4', 's5', 's6', 's7', 's8', 's9'):
    c(f'sl-{e}', 'sl.l', f'lfile=sl.l lname={e} params=0 viewwindows=2')
for i, v in enumerate(['3', '4', '1.5', '2.5', '2/1', '2/0.5', '2/1.5', '2/0.75/yes', '2/0.75/no/300/200',
                       '1/0.75/no/640/480', '1/1/no/500/250', '1/0.75/no/333/211'], 1):
    c(f'vw{i}', 'geo.l', f'lfile=geo.l lname=g2 viewwindows={v}')
for i, cr in enumerate(['-2/2/-1/1', '0/1/0/3', '-1/1/-0.75/0.75', '-10/10/-1/1', '-1/1/-1/1/-0.5/-0.5'], 1):
    for e in ('q4', 'p8', 'p5'):
        c(f'cor{i}-{e}', 'seg.l', f'lfile=seg.l lname={e} viewwindows=2 corners={cr}')
for p in ('2/1', '2/0.5', '2/7/9', '3/0/0/5'):
    c(f'p2-ko-{p.replace("/", "_").replace(".", "p")}', 'sem.l', f'lfile=sem.l lname=ko params={p} viewwindows=2')
c('mi-ko3-maxiter5', 'sem.l', 'lfile=sem.l lname=ko params=3 viewwindows=2 maxiter=5')
c('mi-ko3-passes1', 'sem.l', 'lfile=sem.l lname=ko params=3 viewwindows=2 passes=1')
c('mi-ko3-symxaxis', 'sem.l', 'lfile=sem.l lname=ko params=3 viewwindows=2 symmetry=xaxis')
c('mi-ko3-inside5', 'sem.l', 'lfile=sem.l lname=ko params=3 viewwindows=2 inside=5 outside=7')
open(os.path.join(here, 'cases-misc.txt'), 'w').write('\n'.join(C) + '\n')
