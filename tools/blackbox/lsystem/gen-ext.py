# Extra rounds: protected command arguments during rewriting, classic curves
# with branches and colours, the default palette and size, and odd image
# sizes (aspect handling).  Writes inputs/ext.l and cases-ext.txt.
#   python3 -I gen-ext.py
import os
here = os.path.dirname(os.path.abspath(__file__))
E = [
 ('prot1', 4, 'FC12F', ['1=F']), ('prot2', 4, 'F<12F', ['2=F']), ('prot3', 4, 'D/90D', ['9=+D']),
 ('prot4', 4, 'F@2F+F', ['2=FF']), ('prot5', 4, 'F@Q4F+F', ['Q=FF', '4=FF']), ('prot6', 4, 'FC1.5F+F', ['5=FF']),
 ('ruled', 4, 'D', ['D=D+D']), ('rulem', 4, 'DMD', ['M=G+G']),
 ('plant', 16, 'F', ['F=C2FF-[C3-F+F+F]+[C4+F-F-F]']),
 ('arrow', 6, 'A', ['A=B-A-B', 'B=A+B+A', 'A=', 'B=']),
 ('arrowf', 6, 'F', ['F=G-F-G', 'G=F+G+F']),
 ('dragon', 4, 'FX', ['X=X+YF+', 'Y=-FX-Y']),
 ('levy', 8, 'F', ['F=+F--F+']),
 ('bush', 18, '++++F', ['F=FF-[-F+F+F]+[+F-F-F]']),
 ('degmix', 4, 'F', ['F=D\\30F/60F\\30D+F']),
 ('colcyc', 6, 'F', ['F=<1F+F--F+F']),
]
SIZES = [('400x300', '2'), ('1000x200', '1/0.75/no/1000/200'), ('160x900', '1/0.75/no/160/900'),
         ('777x555', '1/0.75/no/777/555'), ('1024x768', '1/0.75/no/1024/768'), ('50x50', '1/0.75/no/50/50'),
         ('20x20', '1/0.75/no/20/20'), ('12x9', '1/0.75/no/12/9'), ('8x8', '1/0.75/no/8/8'), ('799x601', '1/0.75/no/799/601')]
ORD = {'plant': (3, 4), 'arrow': (5, 6), 'arrowf': (5,), 'dragon': (6, 10), 'levy': (8,), 'bush': (3,), 'degmix': (3,), 'colcyc': (4,)}
L, C = [], ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-ext.py.']
for name, ang, ax, rules in E:
    L += [f'{name} {{', f'  angle {ang}', f'  axiom {ax}'] + [f'  {r}' for r in rules] + ['}']
base = 'only=ext.l,uniq.map type=lsystem lfile=ext.l'
for name, ang, ax, rules in E:
    if name not in ORD:
        C.append(f'x-{name} {base} lname={name} params=1 viewwindows=2 map=uniq.map')
for name, os_ in ORD.items():
    for o in os_:
        C.append(f'x-{name}-o{o} {base} lname={name} params={o} viewwindows=2 map=uniq.map')
for nm, vw in SIZES[1:]:
    for name, o in (('plant', 3), ('dragon', 6), ('degmix', 3)):
        C.append(f'x-{name}-o{o}-{nm} {base} lname={name} params={o} viewwindows={vw} map=uniq.map')
# default palette and default (800x600) size
C.append(f'x-plant-o3-defmap {base} lname=plant params=3 viewwindows=2')
C.append(f'x-plant-o3-defsize {base} lname=plant params=3 map=uniq.map')
C.append(f'x-plant-o3-defall {base} lname=plant params=3')
open(os.path.join(here, 'inputs', 'ext.l'), 'w').write('\n'.join(L) + '\n')
open(os.path.join(here, 'cases-ext.txt'), 'w').write('\n'.join(C) + '\n')
