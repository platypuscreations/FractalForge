# Second round of file-format tests: writes inputs/fnNNN.l and
# cases-fmt2.txt.  As in gen-fmt.py every case has its own file with no
# licence comment.  Every case runs in a work directory that holds only its
# own file and uniq.map (run-case.sh only=...), so XFractint's search of
# other .l files cannot hide what happens.
#   python3 -I gen-fmt2.py
import os
here = os.path.dirname(os.path.abspath(__file__))
T = []
def t(name, text, lname='e', extra='params=0', solo=True, lfile=None):
    T.append((name, text, lname, extra, solo, lfile))
t('rule-nosep', 'e {\n angle 4\n axiom F+F+F\n F F-F\n}\n', extra='params=1')
t('rule-hash', 'e {\n angle 4\n axiom F+#\n # F\n}\n', extra='params=1')
t('rule-hash0', 'e {\n angle 4\n axiom F+#\n # F\n}\n', extra='params=0')
t('rule-nosep2', 'e {\n angle 4\n axiom F+F+F\n F\n}\n', extra='params=1')
t('nolname-solo', 'd {\n angle 4\n axiom F\n}\ne {\n angle 4\n axiom F+F+F\n}\n', lname=None, solo=True)
t('missing-solo', 'e {\n angle 4\n axiom F+F+F\n}\n', lname='zz', solo=True)
t('nofile-solo', None, lname='e', solo=True, lfile='nosuch.l')
t('noext', 'e {\n angle 4\n axiom F+F+F\n}\n', solo=True, lfile='-')
t('upperfile', 'e {\n angle 4\n axiom F+F+F\n}\n', solo=True, lfile='UPPER')
t('nolfile', None, lname='e', solo=True, lfile='')
t('name16', 'abcdefghijklmnop {\n angle 4\n axiom F+F+F\n}\n', lname='abcdefghijklmnop')
t('name17', 'abcdefghijklmnopq {\n angle 4\n axiom F+F+F\n}\n', lname='abcdefghijklmnopq')
t('name24', 'abcdefghijklmnopqrstuvwx {\n angle 4\n axiom F+F+F\n}\n', lname='abcdefghijklmnopqrstuvwx')
t('name31', 'a'*31 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='a'*31)
t('name40', 'b'*40 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='b'*40)
t('name47', 'c'*47 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='c'*47)
t('name48', 'd'*48 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='d'*48)
t('name60', 'g'*60 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='g'*60)
t('name60-short', 'g'*60 + ' {\n angle 4\n axiom F+F+F\n}\n', lname='g'*20)
t('name-punct', 'a-b.c_d(1) {\n angle 4\n axiom F+F+F\n}\n', lname='a-b.c_d(1)')
t('name-twowords', 'e x {\n angle 4\n axiom F+F+F\n}\n', lname='e')
t('name-indent', '   e {\n angle 4\n axiom F+F+F\n}\n', lname='e')
t('noclose3', 'e {\n angle 4\n axiom F+F+F\nangle 6\n', lname='e')
t('noclose4', 'e {\n angle 4\n axiom F+F+F\n\nangle 6\n', lname='e')
t('close-first', 'e {\n angle 4\n } axiom F\n axiom F+F+F\n}\n', lname='e')
t('angle69', 'e {\n angle 6.9\n axiom F+F\n}\n')
t('angle06', 'e {\n angle 06\n axiom F+F\n}\n')
t('anglep6', 'e {\n angle +6\n axiom F+F\n}\n')
t('angle6x', 'e {\n angle 6x\n axiom F+F\n}\n')
t('angle-hex', 'e {\n angle 0x6\n axiom F+F\n}\n')
t('angle6', 'e {\n angle 6\n axiom F+F\n}\n')
for n in (100, 127, 128, 160, 200, 255, 256, 300, 500, 1000, 2000):
    t(f'axlen{n}', 'e {\n angle 4\n axiom ' + 'X'*(n-3) + 'F+F\n}\n')
for n in (100, 160, 200, 255, 256, 300, 500, 1000, 2000):
    t(f'rulelen{n}', 'e {\n angle 4\n axiom A\n A=' + 'X'*(n-3) + 'F+F\n}\n', extra='params=1')
for n in (20, 49, 50, 51, 64, 100, 128, 200, 256, 300):
    t(f'nrules{n}', 'e {\n angle 4\n axiom A\n' + ' X=X\n'*(n-1) + ' A=F+F\n}\n', extra='params=1')
for n in (20, 50, 64, 100, 200, 300, 1000):
    t(f'nlines{n}', 'e {\n' + ' ; c\n'*n + ' angle 4\n axiom F+F+F\n}\n')
C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-fmt2.py.']
for i, (name, text, ln, extra, solo, lfile) in enumerate(T, 1):
    fn = f'fn{i:03d}.l'
    if text is not None:
        open(os.path.join(here, 'inputs', fn), 'w', newline='').write(text)
    lf = fn if lfile is None else (f'fn{i:03d}' if lfile == '-' else (f'FN{i:03d}.L' if lfile == 'UPPER' else lfile))
    args = ['type=lsystem']
    if lf:
        args.append(f'lfile={lf}')
    if ln:
        args.append(f'lname={ln}')
    args += [extra, 'viewwindows=2', 'map=uniq.map']
    pre = (f'only={fn if text is not None else ""},uniq.map ' if solo else '')
    C.append(f'f-{name} {pre}' + ' '.join(args))
open(os.path.join(here, 'cases-fmt2.txt'), 'w').write('\n'.join(C) + '\n')
