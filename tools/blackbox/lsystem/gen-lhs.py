# Which characters may start a rule line?  Writes inputs/lh.l (entries
# hNNN, NNN = character code, each with the rule line "X=F" for character X)
# and cases-lhs.txt.  Codes 59 ';', 61 '=', 123 '{' and 125 '}' are left out
# (comment, separator and braces).  Also adds glued-brace entry-end tests
# as separate files gl1.l, gl2.l.
#   python3 -I gen-lhs.py
import os
here = os.path.dirname(os.path.abspath(__file__))
L = []
C = ['# SPDX-License-Identifier: GPL-3.0-or-later', '# Generated by gen-lhs.py.']
for code in range(33, 127):
    if code in (59, 61, 123, 125):
        continue
    ch = chr(code)
    L += [f'h{code:03d} {{', '  angle 4', '  axiom F+F', f'  {ch}=F', '}']
    C.append(f'h{code:03d} only=lh.l,uniq.map type=lsystem lfile=lh.l lname=h{code:03d} params=1 viewwindows=2 map=uniq.map')
open(os.path.join(here, 'inputs', 'lh.l'), 'w').write('\n'.join(L) + '\n')
open(os.path.join(here, 'inputs', 'gl1.l'), 'w').write('e {\n angle 4\n axiom F+F+F}\n')
open(os.path.join(here, 'inputs', 'gl2.l'), 'w').write('e {\n angle 4\n axiom F+F+F}\n angle 6\n')
C.append('gl1 only=gl1.l,uniq.map type=lsystem lfile=gl1.l lname=e params=0 viewwindows=2 map=uniq.map')
C.append('gl2 only=gl2.l,uniq.map type=lsystem lfile=gl2.l lname=e params=0 viewwindows=2 map=uniq.map')
open(os.path.join(here, 'cases-lhs.txt'), 'w').write('\n'.join(C) + '\n')
